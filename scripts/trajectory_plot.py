# FINAL A* PLANNED PATH VS ACTUAL ROBOT TRAJECTORY
# ============================================================

import csv
import matplotlib.pyplot as plt


# -------------------------------------------------
# READ ACTUAL ROBOT TRAJECTORY
# -------------------------------------------------

actual_x = []
actual_y = []

with open("trajectory.csv", "r") as file:

    reader = csv.DictReader(file)

    for row in reader:

        actual_x.append(float(row["x"]))

        actual_y.append(float(row["y"]))


# -------------------------------------------------
# FINAL A* GENERATED WAYPOINTS
# -------------------------------------------------

# These are the waypoints generated by A* during
# the final successful integrated Webots run.

planned_x = [
    0.000,
    0.000,
    0.325,
    0.325,
    0.325,
    0.200,
    0.200,
    -0.375,
    -0.375,
    -0.350,
    -0.350,
    -0.050,
    -0.050,
    0.000
]

planned_y = [
    0.000,
    -0.175,
    -0.175,
    -0.225,
    -0.200,
    -0.200,
    0.375,
    0.375,
    0.400,
    0.400,
    0.375,
    0.375,
    0.325,
    0.320
]


# -------------------------------------------------
# PLOT
# -------------------------------------------------

plt.figure(figsize=(8, 6))


# -------------------------------------------------
# A* PLANNED PATH
# -------------------------------------------------

plt.plot(planned_x, planned_y, marker="o", linestyle="--", label="A* Planned Path")


# -------------------------------------------------
# ACTUAL ROBOT TRAJECTORY
# -------------------------------------------------

plt.plot(actual_x, actual_y, label="Actual Robot Trajectory")


# -------------------------------------------------
# START POSITION
# -------------------------------------------------

plt.scatter(planned_x[0], planned_y[0], s=120, marker="o", label="Start")


# -------------------------------------------------
# FINAL GOAL
# -------------------------------------------------

plt.scatter(planned_x[-1], planned_y[-1], s=180, marker="*", label="Final Goal")


# -------------------------------------------------
# GRAPH SETTINGS
# -------------------------------------------------

plt.title("A* Planned Path vs Actual Robot Trajectory")

plt.xlabel("X Position (m)")

plt.ylabel("Y Position (m)")

plt.grid()

plt.axis("equal")

plt.legend()

plt.tight_layout()


# -------------------------------------------------
# SAVE UPDATED GRAPH
# -------------------------------------------------

plt.savefig("outputs/planned_vs_actual_trajectory.png", dpi=300, bbox_inches="tight")


